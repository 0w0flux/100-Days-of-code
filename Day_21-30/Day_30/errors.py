# Falsche Einrückung (Tabs/Spaces oder Block falsch eingerückt)
# if x == 5:
# print(x)

#TypeError
# Falscher Datentyp für eine Operation
# "5" + 3

#ValueError
# Richtiger Typ, aber ungültiger Wert
# int("abc")

#NameError
# Variable oder Funktion existiert nicht
# print(x)

#AttributeError
# Objekt besitzt das Attribut nicht
# x = 5
# x.append(3)

#ImportError / ModuleNotFoundError
# Modul oder Objekt kann nicht importiert werden
# import nicht_existierendes_modul

#ZeroDivisionError
# Division durch 0
# 10 / 0

#RuntimeError
